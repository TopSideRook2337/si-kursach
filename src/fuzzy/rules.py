"""База нечётких продукционных правил «ЕСЛИ – ТО» с весовыми коэффициентами.

Формат правила (по методическим указаниям, раздел 3.3.2):
    RULE_j: ЕСЛИ «условие_1» И … И «условие_m» ТО «заключение» (F_j),
где F_j ∈ (0, 1] — весовой коэффициент (степень уверенности эксперта
в истинности заключения). Каждое правило снабжено пояснением.

Правила 1–9 перебирают все сочетания термов «Протяжённости» и «Соблюдения
временных окон». Так как термы каждой переменной покрывают весь универсум,
при любых входных данных срабатывает хотя бы одно из них (полнота базы
правил), и дефаззификация всегда определена.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Rule:
    """Нечёткое продукционное правило.

    Атрибуты:
        conditions: подусловия (имя_переменной, имя_терма), связанные «И».
        conclusion: имя терма выходной переменной «Качество решения».
        weight: весовой коэффициент F.
        explanation: пояснение эксперта.
    """
    conditions: tuple[tuple[str, str], ...]
    conclusion: str
    weight: float
    explanation: str


def R(cond: dict, concl: str, w: float, expl: str) -> Rule:
    return Rule(tuple(cond.items()), concl, w, expl)


